const S: Partial<Record<LangCode, Record<PlannerKey, string>>> = { fr, en };

/** Texte du planning dans la langue donnée (repli : anglais, puis français, puis la clé). */
export function plannerText(lang: LangCode, key: PlannerKey, vars?: Record<string, string | number>): string {
  const raw = S[lang]?.[key] ?? en[key] ?? fr[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
