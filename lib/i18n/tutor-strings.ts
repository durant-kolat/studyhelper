/** Texte du professeur IA dans la langue donnée (repli : français, puis la clé). */
export function tutorText(lang: LangCode, key: TutorKey, vars?: Record<string, string | number>): string {
  // Langues ajoutées (sans textes écrits à la main) : anglais.
  const raw = S[lang]?.[key] ?? S.en[key] ?? S[DEFAULT_LANGUAGE]?.[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
